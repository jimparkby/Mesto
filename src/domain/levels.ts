const bySport = new Map(SPORT_SCALES.map((s) => [s.sport, s]));

export function scaleFor(sport: SportId): SportScale | undefined {
  return bySport.get(sport);
}

/** Во что маппится деление в общей шкале уровней; null, если деления нет. */
export function divisionLevel(sport: SportId, tag: string): Level | null {
  return bySport.get(sport)?.divisions.find((d) => d.tag === tag)?.level ?? null;
}

/** Есть ли в заголовке события метки делений этого вида спорта (сейчас — волейбольные «Д1»–«Д5»). */
export function divisionTagsIn(title: string, sport: SportId): string[] {
  if (sport !== 'volleyball') return [];
  const out = new Set<string>();
  const re = /[дД]\s?-?([1-5])/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(title))) {
    const before = m.index > 0 ? title[m.index - 1] : '';
    const after = title[m.index + m[0].length] ?? '';
    // «Д» внутри слова («годД2») или составная метка («Д12») — не деление.
    if (before && /[\p{L}\p{N}]/u.test(before)) continue;
    if (/\d/.test(after)) continue;
    out.add(`Д${m[1]}`);
  }
  return [...out];
}
