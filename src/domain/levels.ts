import type { Level, SportId } from './types';

/** Одно деление внутри шкалы вида спорта: «Д3», «3.5», «Базовый». */
export interface Division {
  /** Короткая метка для чипа в фильтрах. */
  tag: string;
  /** Человекочитаемое имя для справки. */
  label: string;
  /** Во что деление маппится в общей шкале уровней. */
  level: Level;
  /** Подробное объяснение — показывается в окне с инфо. */
  description: string;
}

export interface SportScale {
  sport: SportId;
  /** Название шкалы, например «Дивизионы ЛВЛ». */
  title: string;
  /** Историческая справка или оговорка. */
  note?: string;
  divisions: Division[];
}

